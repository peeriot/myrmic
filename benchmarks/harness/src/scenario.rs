//! The part of a benchmark that's actually specific to it — everything else (the load sweep,
//! completeness, span collection, report assembly) lives in [`crate::driver`].

use std::collections::HashMap;
use std::time::SystemTime;

use cell_protocol::Sri;
use test_framework::{metrics::CellInteractionMetricsSnapshot, scenario::SwarmTestCtx};
use uuid::Uuid;

/// Which calls a pass produced, and how the driver should find them.
pub enum DispatchedCalls {
    /// the harness dispatched every call itself and already knows each one's send time and
    /// trace id — the common case for an external load producer.
    Known(Vec<(SystemTime, Uuid)>),
    /// calls were generated by a producer running *inside* the swarm (e.g. a timer-driven
    /// cell), so the harness never assigned them a trace id up front. The driver instead
    /// discovers them by querying every span created since the pass started and grouping by
    /// trace id — see [`crate::driver`]'s `discover_calls`.
    Discovered,
}

/// Result of dispatching one load pass: which calls were produced (see [`DispatchedCalls`]), and
/// how many calls `load * timeout` implies should have happened over the (fixed, deterministic)
/// dispatch window — the shortfall against the actual call count is ingestion loss.
pub struct DispatchOutcome {
    pub calls: DispatchedCalls,
    pub expected_messages: u64,
}

/// A specific benchmark's topology, dispatch logic, and reporting shape. The generic sweep
/// driver ([`crate::driver::run`]) implements everything else: looping over `loads`, waiting
/// for completeness between passes, collecting spans, and assembling the report.
///
/// `async fn` in this trait doesn't need a `Send` bound: it's driven directly from a single
/// `#[tokio::main]` future in `main`, never boxed into a `dyn` trait object or spawned onto
/// another task.
#[allow(async_fn_in_trait)]
pub trait BenchmarkScenario {
    /// benchmark-specific config, deserialized from the config file's `[specialized]` table.
    type Specialized: serde::de::DeserializeOwned;

    /// title shown on the report.
    fn title(&self) -> String;

    /// Spawns the swarm process and deploys every cell. Called once; the same swarm process
    /// and deployed cells are reused for every pass in the load sweep.
    async fn build_ctx(&self, specialized: &Self::Specialized) -> SwarmTestCtx;

    /// Run-config parameters to report, beyond the "Load (commands/sec)"/"Timeout (seconds)"
    /// the driver already adds per pass.
    fn run_params(&self, specialized: &Self::Specialized) -> Vec<(String, String)>;

    /// Every cell's `Sri` mapped to a human-readable display name (e.g. its SRN) — `Sri` is a
    /// one-way hash of that name, so this is the only place that knowledge exists.
    fn sri_names(&self, specialized: &Self::Specialized) -> HashMap<Sri, String>;

    /// The full hop chain each call is expected to pass through, for trace-completeness — e.g.
    /// `[object_sris, zone_sris, [central_sri]]`. A call's trace counts as successful only if it
    /// has a span matching at least one `Sri` in every entry.
    fn expected_hops(&self, specialized: &Self::Specialized) -> Vec<Vec<Sri>>;

    /// Dispatches one load pass into the already-built swarm. `pass_index` is this pass's
    /// 0-based position in the sweep (`loads[pass_index] == load`), for benchmarks that want to
    /// tag dispatched calls with it (e.g. for log correlation).
    async fn dispatch(
        &self,
        ctx: &SwarmTestCtx,
        specialized: &Self::Specialized,
        pass_index: usize,
        load: u64,
        timeout: u64,
    ) -> DispatchOutcome;

    /// Hop-coverage rows (label, processed count) computed from this pass's metrics delta —
    /// e.g. `("tier 1 object processed commands", metrics_delta.matching_sri(&asset_sris).commands_received)`.
    fn hop_coverage(
        &self,
        specialized: &Self::Specialized,
        metrics_delta: &CellInteractionMetricsSnapshot,
    ) -> Vec<(String, u64)>;
}
